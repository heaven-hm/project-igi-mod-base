#!/usr/bin/env python3
"""Validate and emit the small compile-time native contract used by the demo.

The complete generated catalogue is checked by test_generated_natives.py.  This
script deliberately emits only the ten calls the demo exposes, so the demo
test remains fast and does not call an IGI process.
"""
from pathlib import Path
import csv
import re

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "data/igi-natives.csv"
CASES = ROOT / "tests/demo-natives.tsv"
OUTPUT = ROOT / "tests/generated_demo_natives.cpp"

def read_tsv(path):
    with path.open(encoding="utf-8", newline="") as f:
        return [r for r in csv.reader((x for x in f if not x.startswith("#")), delimiter="\t") if r]

def main():
    with MANIFEST.open(encoding="utf-8", newline="") as f:
        source = {r["address"].lower(): r for r in csv.DictReader(f)}
    cases = read_tsv(CASES)
    if len(cases) != 10:
        raise SystemExit(f"expected exactly 10 demo natives, found {len(cases)}")
    seen = set()
    declarations = []
    for api, domain, name, address, signature in cases:
        if api in seen:
            raise SystemExit(f"duplicate demo API: {api}")
        seen.add(api)
        row = source.get(address.lower())
        if row is None:
            raise SystemExit(f"{name}: address {address} is absent from the generated catalogue")
        # Manifest columns: domain, api, address, name, signature, verification.
        if (row["name"], row["signature"]) != (name, signature):
            raise SystemExit(f"{name}: demo contract does not match manifest: {row}")
        prefix, params = signature.split("(", 1)
        match = re.fullmatch(r"(.+?)([A-Za-z_]\w*)", prefix.rstrip())
        if not match:
            raise SystemExit(f"unsupported signature: {signature}")
        result, _ = match.groups()
        params = params[:-1]
        declarations.append((domain, api, result, params))

    lines = [
        '// Generated by tools/generate_demo_native_tests.py; do not edit.',
        '#include "igi_sdk/IGI.hpp"',
        '#include <cstddef>',
        '#include <type_traits>',
        '',
        'namespace {',
    ]
    for domain, api, result, params in declarations:
        # The Python side compares the complete authoritative signature.  The
        # C++ side deliberately checks only that the generated public symbol is
        # addressable; spelling opaque IGI structs again here would create a
        # second ABI parser and make this test implementation-coupled.
        lines.append(f"static_assert(std::is_pointer_v<decltype(&IGI::{domain}::{api})>);")
    lines += ['}', '', 'int main() { return static_cast<int>(IGI::NativeBindingCount() < 10); }', '']
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"validated and generated {len(cases)} demo native signature tests")

if __name__ == "__main__":
    main()
